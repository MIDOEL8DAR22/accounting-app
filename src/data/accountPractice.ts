export const DIFFICULTY_LABELS = ['مبتدئ', 'سهل', 'متوسط', 'متقدم', 'تحدّي']

export function mixedOrder(): PracticeQuestion[] {
  const groups = new Map<number, PracticeQuestion[]>()
  for (const q of MIXED_QUESTIONS) {
    const arr = groups.get(q.difficulty) ?? []
    arr.push(q)
    groups.set(q.difficulty, arr)
  }
  const out: PracticeQuestion[] = []
  for (const d of [1, 2, 3, 4, 5]) {
    const group = groups.get(d) ?? []
    out.push(...group.sort(() => Math.random() - 0.5))
  }
  return out
}