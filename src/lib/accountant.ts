function detectEntry(q: string): EntryReply | null {
  const t = q.replace(/[\u0660-\u0669]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
  const amt = parseAmountText(t)
  const amountLabel = amt !== null ? formatAmount(amt) : undefined

  const has = (...ws: string[]) => ws.some((w) => t.includes(w))

  if (/^(ما|ماهي|ما هي|إيه|اي|ايه|كيف|ازاي|اإيه|اشرح|عرفني|عرفنى|فرق|بين)/.test(t.trim()) && !has('قيد')) return null

  if (has('بضاعة آخر المدة') || has('آخر المدة') || has('اخر المدة') || has('جرد')) {
    return { debit: 'بضاعة آخر المدة', credit: 'ملخص المتاجرة (الجرد)', entryNote: 'تسوية نهاية الفترة: البضاعة اللي فضلت في المخزن تطلع أصل وتقلّل تكلفة البضاعة المباعة.', amountLabel }
  }
  if (has('بيع', 'باع', 'بعت', 'مبيعات', 'فاتورة بيع', 'فواتير')) {
    if (has('آجل', 'بالدين', 'عميل', 'دين')) return { debit: 'العملاء', credit: 'المبيعات', entryNote: 'البيع بالأجل: الدين بيبقى ذمة للعميل.' }
    return { debit: 'النقدية', credit: 'المبيعات', entryNote: 'البيع النقدي: فلوس جت في الصندوق فورًا.' }
  }
  if (has('مشتريات', 'اشترى', 'اشتريت', 'شريت', 'شراء')) {
    if (has('آجل', 'بالدين', 'مورد', 'دائن')) return { debit: 'المشتريات', credit: 'الموردون', entryNote: 'الشراء بالدين: التزام على المشتريات.' }
    return { debit: 'المشتريات', credit: 'النقدية' }
  }
  if (has('استلم') && has('عميل', 'مدين')) return { debit: 'النقدية', credit: 'العملاء', entryNote: 'تقسيط الدين: العميل سدد اللي عليه.' }
  if (has('سدد', 'سداد', 'دفع') && has('مورد', 'دائن')) return { debit: 'الموردون', credit: 'النقدية', entryNote: 'سداد دين المورد: قلّ التزام الموردين.' }
  if (has('سحب', 'مسحوبات', 'صاحب', 'مالك')) return { debit: 'المسحوبات', credit: 'النقدية', entryNote: 'المسحوبات بقلّل رأس المال — مش مصروف.' }
  if (has('رأس المال', 'راس المال', 'راس مال')) return { debit: 'النقدية', credit: 'رأس المال' }
  if (has('إيجار', 'ايجار', 'ريع')) return { debit: 'مصروف الإيجار', credit: 'النقدية' }
  if (has('مرتبات', 'رواتب', 'مرتب', 'أجور', 'اجور')) return { debit: 'مصروف المرتبات', credit: 'النقدية' }
  if (has('كهرباء', 'مياه')) return { debit: 'مصروف الكهرباء', credit: 'النقدية' }
  if (has('وقود', 'سولار', 'بنزين', 'ديزل')) return { debit: 'مصروف الوقود', credit: 'النقدية' }
  if (has('إنترنت', 'انترنت', 'اتصالات')) return { debit: 'مصروف الإنترنت', credit: 'النقدية' }
  if (has('إعلان', 'اعلان', 'دعاية', 'دعايا')) return { debit: 'مصروف الإعلان', credit: 'النقدية' }
  if (has('صيانة', 'إصلاح')) return { debit: 'مصروف الصيانة', credit: 'النقدية' }
  if (has('تأمين')) return { debit: 'تأمينات لدى الغير', credit: 'النقدية', entryNote: 'تأمين مدفوع للغير — أصل مؤقت بيُستهلك طول الفترة.' }
  if (has('إهلاك', 'اهلاك')) return { debit: 'مصروف الإهلاك', credit: 'مجمع إهلاك (الآلات)', entryNote: 'توزيع تكلفة الأصل على عمره الإنتاجي — مجمع الإهلاك حساب دائن مقابل.' }
  if (has('قرض', 'اقتراض', 'استلف', 'سلفة')) return { debit: 'النقدية', credit: 'قرض (التزام)' }
  if (has('خصم مسموح', 'خصم مسموح به')) return { debit: 'خصم مسموح به', credit: 'العملاء', entryNote: 'خصم منّيتك لا بإستحقاق — مصروف على الشركة.' }
  if (has('خصم مكتسب', 'خصم مكتسب')) return { debit: 'الموردون', credit: 'خصم مكتسب', entryNote: 'خصم خدته من المورد — بيرفع أرباحك ببلاش.' }
  return null
}

