export function askAccountant(input: string): BotReply {
  const q = input.trim()
  const entry = detectEntry(q)
  if (entry) {
    const lines = [
      'يا محاسب، في الشغل الحقيقي القيد المرجع ده بيتكتب كالآتي:',
      '',
      `من حـ ${entry.debit}${entry.amountLabel ? ` ${entry.amountLabel}` : ''}`,
      `        إلى حـ ${entry.credit}${entry.amountLabel ? ` ${entry.amountLabel}` : ''}`,
    ]
    if (entry.entryNote) lines.push('', entry.entryNote)
    return { text: lines.join('\n'), entry }
  }

  const faq = FAQ.find((f) => f.keys.some((k) => q.includes(k)))
  if (faq) return { text: faq.text }

  return { text: FALLBACK }
}

